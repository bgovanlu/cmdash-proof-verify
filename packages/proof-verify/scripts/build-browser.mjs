#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
/**
 * Builds browser/verify.js: ONE ES module, with no bundler dependency, made
 * by concatenating the isomorphic modules of lib/ in dependency order.
 *
 *   node scripts/build-browser.mjs           write browser/verify.js
 *   node scripts/build-browser.mjs --check   exit 1 if browser/verify.js is stale
 *
 * How: every relative `import ... from './x.mjs'` is removed, and `export`
 * is dropped from the declarations of every module but the entry, whose
 * exports become the build's. That is sound only because every top-level name
 * is unique across the modules and nothing else is imported, so the build
 * REFUSES when two modules declare the same top-level name, when any other
 * import remains, or when a Node-only construct (node:, require, process,
 * Buffer) would reach the browser. test/browser.test.js runs every vector
 * through the built file and fails when it differs from a fresh build.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BROWSER_OUT = join(PKG, 'browser', 'verify.js');

/** Dependency order: each module only imports modules listed before it. */
export const BROWSER_MODULES = Object.freeze([
  'bytes.mjs',
  'escape.mjs',
  'canonical.mjs',
  'json.mjs',
  'schema.mjs',
  'ed25519.mjs',
  'merkle.mjs',
  'note.mjs',
  'backend-web.mjs',
  'core.mjs',
  'collector.mjs',
  'consistency.mjs',
  'browser-entry.mjs',
]);
const ENTRY = 'browser-entry.mjs';

const IMPORT_RE = /^import\s+\{[^}]*\}\s+from\s+'\.\/([a-z0-9-]+\.mjs)';\n/gm;
const DECLARATION_RE =
  /^(?:export\s+)?(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm;

const readLibModule = (name) => readFileSync(join(PKG, 'lib', name), 'utf8');

/** The build's text. `readModule` is injectable so that tests can prove each refusal fires. */
export function buildBrowser(readModule = readLibModule) {
  const seen = new Map();
  const parts = [
    '// SPDX-License-Identifier: Apache-2.0',
    '// @cmdash/proof-verify: the browser build (one ES module, WebCrypto by default).',
    '// GENERATED by packages/proof-verify/scripts/build-browser.mjs from lib/*.mjs. Do not edit:',
    '// run `npm run build:browser -w packages/proof-verify`. test/browser.test.js fails when this file',
    '// differs from a fresh build. Spec: docs/specs/proof-receipt-v0.md. Verification never needs CMDash.',
    '',
  ];
  BROWSER_MODULES.forEach((name, position) => {
    let src = readModule(name);
    src = src.replace(/^\/\/ SPDX-License-Identifier: Apache-2\.0\n/, '');
    src = src.replace(IMPORT_RE, (match, from) => {
      const at = BROWSER_MODULES.indexOf(from);
      if (at < 0 || at >= position)
        throw new Error(`build-browser: ${name} imports ${from}, which is not built before it`);
      return '';
    });
    // The guards read the code, not its comments (which may well mention what they refuse).
    const code = src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
    if (/^\s*import[\s{*]/m.test(code) || /\bimport\s*\(/.test(code))
      throw new Error(`build-browser: ${name} keeps an import the build cannot inline`);
    if (/['"]node:|\brequire\s*\(|\bprocess\.|\bBuffer\b/.test(code))
      throw new Error(`build-browser: ${name} uses a Node-only construct`);
    for (const m of src.matchAll(DECLARATION_RE)) {
      if (seen.has(m[1]))
        throw new Error(
          `build-browser: top-level name ${m[1]} is declared in both ${seen.get(m[1])} and ${name}`,
        );
      seen.set(m[1], name);
    }
    if (name !== ENTRY) {
      if (/^export\s+(?:\{|\*|default)/m.test(src))
        throw new Error(`build-browser: ${name} has an export list the build cannot flatten`);
      src = src.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|class)\s)/gm, '');
    }
    parts.push(
      `// --- lib/${name} ${'-'.repeat(Math.max(0, 70 - name.length))}`,
      src.trimEnd(),
      '',
    );
  });
  // Exactly one trailing newline: with prettier-formatted modules this keeps the build stable under the
  // repo's prettier, so `npm run format` at the root does not make the committed build drift from a fresh
  // one (test/browser.test.js also refuses two blank lines in a row, the other thing prettier rewrites).
  return `${parts.join('\n').trimEnd()}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const built = buildBrowser();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(BROWSER_OUT, 'utf8');
    } catch {
      current = '';
    }
    if (current !== built) {
      console.error(
        'browser/verify.js is stale: run `npm run build:browser -w packages/proof-verify` and commit it.',
      );
      process.exit(1);
    }
    console.log(`browser/verify.js is up to date (${Buffer.byteLength(built)} bytes).`);
  } else {
    writeFileSync(BROWSER_OUT, built);
    console.log(`wrote browser/verify.js (${Buffer.byteLength(built)} bytes)`);
  }
}
